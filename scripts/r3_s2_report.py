"""R3-S2: build the draft of report pages 3-6 from its template and the project's evidence files.

    python scripts/r3_s2_report.py all        facts + figures + draft (the usual command)
    python scripts/r3_s2_report.py facts      compute and print the facts only
    python scripts/r3_s2_report.py figures    redraw the two report figures
    python scripts/r3_s2_report.py render     fill the template and write the draft and the fact table

Edit `reports/final/pages_3_6_template.md`. The draft `pages_3_6_draft.md` and `pages_3_6_facts.json` are generated and must not be edited by hand.
Every `{{key}}` in the template is a number read or recomputed from a source file; rendering fails on an unknown key or when two sources disagree.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("command", choices=("all", "facts", "figures", "render"))
    p.add_argument("--root", default=str(ROOT))
    args = p.parse_args(argv)
    root = Path(args.root)
    out = root / "reports" / "final"
    out.mkdir(parents=True, exist_ok=True)
    (out / "figures").mkdir(exist_ok=True)
    from echoproof.reporting import facts as F, figures as G, render as R
    facts = F.compute_facts(root)
    if args.command == "facts":
        for key, entry in facts.items():
            print(f"{key:36s} {entry['text'][:70]:70s} <- {entry['source']}")
        return
    if args.command in ("all", "figures"):
        a = G.methodology_diagram(facts, out / "figures" / "methodology_diagram")
        b = G.split_composition(root, out / "figures" / "split_composition")
        print("figures:", [Path(f).name for f in a["files"] + b["files"]])
    if args.command in ("all", "render"):
        template_path = out / "pages_3_6_template.md"
        template = template_path.read_bytes().decode("utf-8").replace("\r\n", "\n")
        import re
        body = re.sub(r"\A<!--.*?-->\s*", "", template, count=1, flags=re.S)                       # drop the template's own instructions
        text, used = R.render(body, facts)
        header = ("<!-- GENERATED by scripts/r3_s2_report.py from reports/final/pages_3_6_template.md and the project's evidence files. "
                  "Do not edit this file: edit the template and rerun. Sources of every number: pages_3_6_facts.json. -->")
        text = header + "\n\n" + text
        (out / "pages_3_6_draft.md").write_bytes(text.encode("utf-8"))
        unused = R.unused_facts(facts, used)
        record = {"schema_version": 1, "task": "R3-S2", "template": "reports/final/pages_3_6_template.md",
                  "template_sha256": hashlib.sha256(template.encode("utf-8")).hexdigest(),
                  "draft_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
                  "facts_used": len(used), "facts_unused": unused, "facts": {k: {x: facts[k][x] for x in ("text", "source", "how")} for k in sorted(facts)}}
        (out / "pages_3_6_facts.json").write_text(json.dumps(record, indent=2, sort_keys=True), encoding="utf-8")
        print(f"draft written: {len(text.split())} words, {len(used)} facts used, {len(unused)} computed but not cited")


if __name__ == "__main__":
    main()
